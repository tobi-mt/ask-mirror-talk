function mirrortalk_seo_admin_actions() {
    if (!current_user_can('manage_mirrortalk_seo')) return;
    if (isset($_POST['mt_add_redirect']) && check_admin_referer('mirrortalk_redirects')) {
        $source = '/' . ltrim((string) sanitize_text_field(wp_unslash($_POST['redirect_source'] ?? '')), '/');
        $target = esc_url_raw(wp_unslash($_POST['redirect_target'] ?? ''));
        if ($source !== '/' && $target && wp_validate_redirect($target, false)) {
            $rules = (array) get_option('mirrortalk_redirects', array());
            $rules[$source] = array('target' => $target, 'code' => 301, 'hits' => 0, 'created' => time(), 'automatic' => false);
            update_option('mirrortalk_redirects', $rules, false); mirrortalk_indexnow_queue_url(home_url($source));
        }
        wp_safe_redirect(admin_url('admin.php?page=mirror-talk-seo&updated=redirect')); exit;
    }
    if (isset($_GET['mt_delete_redirect'], $_GET['_wpnonce']) && wp_verify_nonce(sanitize_text_field(wp_unslash($_GET['_wpnonce'])), 'mt_delete_redirect')) {
        $key = rawurldecode(sanitize_text_field(wp_unslash($_GET['mt_delete_redirect']))); $rules = (array) get_option('mirrortalk_redirects', array()); unset($rules[$key]); update_option('mirrortalk_redirects', $rules, false);
        wp_safe_redirect(admin_url('admin.php?page=mirror-talk-seo')); exit;
    }
    if (isset($_POST['mt_run_crawler']) && check_admin_referer('mirrortalk_run_crawler')) {
        mirrortalk_runtime_queue('mirrortalk_seo_crawl_continue'); wp_safe_redirect(admin_url('admin.php?page=mirror-talk-seo&updated=crawl-queued')); exit;
    }
    if (isset($_GET['mt_rollback_post'], $_GET['snapshot'], $_GET['_wpnonce']) && wp_verify_nonce(sanitize_text_field(wp_unslash($_GET['_wpnonce'])), 'mt_seo_rollback')) {
        $post_id = absint($_GET['mt_rollback_post']); $index = absint($_GET['snapshot']);
        if (current_user_can('edit_post', $post_id)) {
            $history = (array) get_post_meta($post_id, '_mirrortalk_seo_history', true);
            if (isset($history[$index])) foreach (array('title' => '_mirrortalk_meta_title', 'description' => '_mirrortalk_meta_description', 'noindex' => '_mirrortalk_noindex') as $key => $meta) update_post_meta($post_id, $meta, $history[$index][$key] ?? '');
        }
        wp_safe_redirect(get_edit_post_link($post_id, 'raw')); exit;
    }
}
add_action('admin_init', 'mirrortalk_seo_admin_actions', 20);

