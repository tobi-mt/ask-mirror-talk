/* Editorial intelligence: zero-config suggestions plus optional private AI. */
function mirrortalk_seo_editorial_analysis($post) {
    $plain = trim(preg_replace('/\s+/', ' ', wp_strip_all_tags(strip_shortcodes($post->post_content))));
    $words = str_word_count($plain); $title = get_the_title($post); $issues = array();
    $title_length = function_exists('mb_strlen') ? mb_strlen($title) : strlen($title);
    if ($title_length < 25) $issues[] = __('The title may be too vague for searchers.', 'astra-child');
    if ($title_length > 65) $issues[] = __('The title may truncate in search results.', 'astra-child');
    if ($words < 500) $issues[] = __('Add a useful summary, key takeaways or transcript-derived context.', 'astra-child');
    if (!preg_match('/<h2\b/i', $post->post_content)) $issues[] = __('Add descriptive section headings for readers and search engines.', 'astra-child');
    if (!preg_match('/href=["\']' . preg_quote(home_url('/'), '/') . '/i', $post->post_content)) $issues[] = __('Add a relevant internal topic or episode link.', 'astra-child');
    $description = wp_trim_words($plain, 26, '');
    return array('score' => max(0, 100 - count($issues) * 12), 'issues' => $issues, 'suggested_title' => $title, 'suggested_description' => $description, 'words' => $words);
}

