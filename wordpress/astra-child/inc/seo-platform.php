/* SEO history and safe rollback. */
function mirrortalk_seo_snapshot($post_id) {
    $snapshot = array('time' => time(), 'user' => get_current_user_id(), 'title' => get_post_meta($post_id, '_mirrortalk_meta_title', true), 'description' => get_post_meta($post_id, '_mirrortalk_meta_description', true), 'noindex' => get_post_meta($post_id, '_mirrortalk_noindex', true));
    $history = (array) get_post_meta($post_id, '_mirrortalk_seo_history', true);
    $last = end($history);
    if (!$last || wp_json_encode(array_diff_key($last, array('time' => 1, 'user' => 1))) !== wp_json_encode(array_diff_key($snapshot, array('time' => 1, 'user' => 1)))) {
        $history[] = $snapshot; update_post_meta($post_id, '_mirrortalk_seo_history', array_slice($history, -25));
    }
}
add_action('save_post', function ($post_id) { if (!wp_is_post_revision($post_id)) mirrortalk_seo_snapshot($post_id); }, 100);

