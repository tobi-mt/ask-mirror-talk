/* Redirect manager: automatically remember old slugs and serve explicit rules. */
add_action('post_updated', function ($post_id, $after, $before) {
    if ($after->post_status !== 'publish' || $before->post_name === $after->post_name) return;
    $old = wp_make_link_relative(get_permalink($before));
    $rules = (array) get_option('mirrortalk_redirects', array());
    $rules[$old] = array('target' => get_permalink($after), 'code' => 301, 'hits' => 0, 'created' => time(), 'automatic' => true);
    update_option('mirrortalk_redirects', $rules, false);
}, 10, 3);
function mirrortalk_redirect_request() {
    if (is_admin()) return;
    $path = wp_parse_url(home_url(add_query_arg(array())), PHP_URL_PATH);
    $rules = (array) get_option('mirrortalk_redirects', array());
    if (empty($rules[$path]['target'])) return;
    $rules[$path]['hits'] = (int) ($rules[$path]['hits'] ?? 0) + 1;
    update_option('mirrortalk_redirects', $rules, false);
    wp_safe_redirect($rules[$path]['target'], in_array((int) $rules[$path]['code'], array(301, 302, 307, 308), true) ? (int) $rules[$path]['code'] : 301, 'Mirror Talk SEO'); exit;
}
