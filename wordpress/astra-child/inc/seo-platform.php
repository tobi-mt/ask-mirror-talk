        array('methods' => WP_REST_Server::CREATABLE, 'permission_callback' => function () { return current_user_can('manage_mirrortalk_seo'); }, 'callback' => function ($request) {
            $rows = array_slice((array) $request->get_json_params(), 0, 10000); $clean = array();
            foreach ($rows as $row) $clean[] = array('date' => sanitize_text_field($row['date'] ?? ''), 'engine' => in_array(($row['engine'] ?? ''), array('google', 'bing'), true) ? $row['engine'] : 'google', 'query' => sanitize_text_field($row['query'] ?? ''), 'page' => esc_url_raw($row['page'] ?? ''), 'clicks' => max(0, (int) ($row['clicks'] ?? 0)), 'impressions' => max(0, (int) ($row['impressions'] ?? 0)), 'position' => max(0, (float) ($row['position'] ?? 0)));
            update_option('mirrortalk_search_performance', $clean, false); return rest_ensure_response(array('stored' => count($clean)));
        }),
    ));
    register_rest_route('mirror-talk/v1', '/content-analysis/(?P<id>\d+)', array('methods' => WP_REST_Server::READABLE, 'permission_callback' => function ($request) { return current_user_can('edit_post', (int) $request['id']); }, 'callback' => function ($request) { $post = get_post((int) $request['id']); return $post ? rest_ensure_response(mirrortalk_seo_editorial_analysis($post)) : new WP_Error('not_found', __('Content not found.', 'astra-child'), array('status' => 404)); }));
});

function mirrortalk_seo_rank_summary() {
    $rows = (array) get_option('mirrortalk_search_performance', array());
    usort($rows, function ($a, $b) { return ((int) ($b['impressions'] ?? 0)) <=> ((int) ($a['impressions'] ?? 0)); });
    return array_slice($rows, 0, 20);
}

