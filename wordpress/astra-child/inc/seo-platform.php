define('MIRRORTALK_SEO_PLATFORM_VERSION', '1.3.0');

function mirrortalk_seo_option($key, $default = '') {
    $settings = (array) get_option('mirrortalk_seo_platform', array());
    return array_key_exists($key, $settings) ? $settings[$key] : $default;
}

function mirrortalk_seo_public_post_types() {
    $types = get_post_types(array('public' => true), 'names');
    unset($types['attachment']);
    return array_values($types);
}

function mirrortalk_seo_install() {
    $role = get_role('administrator');
    if ($role) $role->add_cap('manage_mirrortalk_seo');
    $editor = get_role('editor');
    if ($editor) $editor->add_cap('manage_mirrortalk_seo');
    add_role('mirror_talk_seo_manager', __('SEO Manager', 'astra-child'), array(
        'read' => true, 'edit_posts' => true, 'edit_published_posts' => true,
        'upload_files' => true, 'manage_mirrortalk_seo' => true,
    ));
    if (!get_option('mirrortalk_indexnow_key')) {
        update_option('mirrortalk_indexnow_key', wp_generate_password(32, false, false), false);
    }
    mirrortalk_seo_schedule_events();
    flush_rewrite_rules(false);
}
