/* Mirror Talk is authoritative. Buffer only the head fragment, remove parallel
 * SEO suites' duplicate public metadata, then render one canonical graph. */
function mirrortalk_authoritative_head_buffer_start() {
    if (!mirrortalk_seo_authoritative() || is_admin() || isset($_GET['mirror_player'])) return;
    ob_start();
}
function mirrortalk_authoritative_head_buffer_end() {
    if (!mirrortalk_seo_authoritative() || is_admin() || isset($_GET['mirror_player']) || !ob_get_level()) return;
    $head = ob_get_clean();
    $patterns = array(
        '#<link\b[^>]*\brel=["\']canonical["\'][^>]*>\s*#i',
        '#<meta\b[^>]*\bname=["\']description["\'][^>]*>\s*#i',
        '#<meta\b[^>]*\bproperty=["\'](?:og:|article:)[^"\']+["\'][^>]*>\s*#i',
        '#<meta\b[^>]*\bname=["\']twitter:[^"\']+["\'][^>]*>\s*#i',
        '#<link\b[^>]*\brel=["\']alternate["\'][^>]*\btype=["\']text/plain["\'][^>]*>\s*#i',
        '#<script\b[^>]*type=["\']application/ld\+json["\'][^>]*>.*?</script>\s*#is',
    );
    echo preg_replace($patterns, '', $head);
    mirrortalk_seo_head();
}
add_action('wp_head', 'mirrortalk_authoritative_head_buffer_start', -PHP_INT_MAX);
add_action('wp_head', 'mirrortalk_authoritative_head_buffer_end', PHP_INT_MAX);

/* IndexNow: publish/delete/redirect changes are submitted in a short batch. */
function mirrortalk_indexnow_queue_url($url) {
    if (!$url || strpos($url, home_url('/')) !== 0) return;
    $queue = (array) get_option('mirrortalk_indexnow_queue', array());
    $queue[esc_url_raw($url)] = time();
    update_option('mirrortalk_indexnow_queue', array_slice($queue, -10000, null, true), false);
    if (!wp_next_scheduled('mirrortalk_indexnow_submit')) wp_schedule_single_event(time() + 60, 'mirrortalk_indexnow_submit');
}
add_action('transition_post_status', function ($new, $old, $post) {
    if ($new === 'publish' || $old === 'publish') mirrortalk_indexnow_queue_url(get_permalink($post));
}, 10, 3);
add_action('before_delete_post', function ($post_id) { mirrortalk_indexnow_queue_url(get_permalink($post_id)); });
function mirrortalk_indexnow_submit() {
    $queue = array_keys((array) get_option('mirrortalk_indexnow_queue', array()));
    if (!$queue) return;
    $key = (string) get_option('mirrortalk_indexnow_key');
    $response = wp_remote_post('https://api.indexnow.org/indexnow', array('timeout' => 6, 'headers' => array('Content-Type' => 'application/json'), 'body' => wp_json_encode(array(
        'host' => wp_parse_url(home_url('/'), PHP_URL_HOST), 'key' => $key,
        'keyLocation' => home_url('/' . $key . '.txt'), 'urlList' => array_slice($queue, 0, 10000),
    ))));
    update_option('mirrortalk_indexnow_last', array('time' => time(), 'status' => is_wp_error($response) ? $response->get_error_message() : wp_remote_retrieve_response_code($response), 'count' => count($queue)), false);
    if (!is_wp_error($response) && wp_remote_retrieve_response_code($response) < 300) delete_option('mirrortalk_indexnow_queue');
}
add_action('mirrortalk_indexnow_submit', function(){mirrortalk_runtime_run('indexnow','mirrortalk_indexnow_submit',10*MINUTE_IN_SECONDS);});

