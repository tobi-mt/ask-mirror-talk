function mirrortalk_seo_description_candidate($post) {
    $plain = trim(preg_replace('/\s+/', ' ', wp_strip_all_tags(strip_shortcodes($post->post_excerpt ?: $post->post_content))));
    if (strlen($plain) < 80) return '';
    $candidate = function_exists('mb_substr') ? mb_substr($plain, 0, 158) : substr($plain, 0, 158);
    if (strlen($plain) > strlen($candidate)) $candidate = preg_replace('/\s+\S*$/u', '', $candidate);
    return rtrim($candidate, " \t\n\r\0\x0B,;:-") . (strlen($plain) > strlen($candidate) ? '…' : '');
}

