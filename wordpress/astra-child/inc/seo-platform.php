/* Own the two key editorial routes even when the WordPress Reading settings or
 * an old page slug have not been updated after deployment. */
function mirrortalk_owned_editorial_templates($template) {
    if (is_front_page() && empty($_GET['legacy_home'])) {
        $home = get_stylesheet_directory() . '/page-templates/mirror-talk-home.php';
        if (is_readable($home)) return $home;
    }
    if (get_query_var('mirror_blog')) {
        global $wp_query;
        $wp_query->is_home = true; $wp_query->is_page = false; $wp_query->is_404 = false;
        $blog = get_stylesheet_directory() . '/home.php';
        if (is_readable($blog)) return $blog;
    }
    return $template;
}
