    if (get_option('mirrortalk_seo_platform_version') === MIRRORTALK_SEO_PLATFORM_VERSION) return;
    mirrortalk_seo_install();
    update_option('mirrortalk_seo_platform_version', MIRRORTALK_SEO_PLATFORM_VERSION, false);
});

/* AIOSEO serves llms.txt as a physical web-root file, which takes precedence
 * over WordPress rewrites. Remove only those generated discovery files and
 * disable only that generator so Mirror Talk remains the single owner. */
function mirrortalk_claim_llms_ownership() {
    if (get_option('mirrortalk_llms_owner_version') === MIRRORTALK_SEO_PLATFORM_VERSION) return;
    if (function_exists('aioseo')) {
        try {
            $aioseo = aioseo();
            if (isset($aioseo->options->sitemap->llms->enable)) {
                $aioseo->options->sitemap->llms->enable = false;
                $aioseo->options->save(true);
            }
            if (!empty($aioseo->llms)) {
                if (!empty($aioseo->actionScheduler)) {
                    $aioseo->actionScheduler->unschedule($aioseo->llms->llmsTxtSingleAction);
                    $aioseo->actionScheduler->unschedule($aioseo->llms->llmsTxtRecurrentAction);
                }
                $fs = $aioseo->core->fs;
                if ($fs->isWpfsValid()) {
                    foreach (array(false, true) as $full) {
                        $file = $aioseo->llms->getFilePath($full);
                        if ($fs->fs->exists($file)) $fs->fs->delete($file, false, 'f');
                    }
                }
            }
        } catch (Throwable $error) {
            error_log('Mirror Talk could not claim llms.txt ownership: ' . $error->getMessage());
            return;
        }
    }
    foreach (array('llms.txt', 'llms-full.txt') as $filename) {
        $file = trailingslashit(dirname(WP_CONTENT_DIR)) . $filename;
        if (!is_file($file)) continue;
        $sample = file_get_contents($file, false, null, 0, 4096);
        if ($sample !== false && stripos($sample, 'Generated by All in One SEO') !== false) wp_delete_file($file);
        if (is_file($file)) {
            error_log('Mirror Talk could not remove the existing AIOSEO ' . $filename . ' file.');
            return;
        }
    }
    update_option('mirrortalk_llms_owner_version', MIRRORTALK_SEO_PLATFORM_VERSION, false);
}
add_action('admin_init', 'mirrortalk_claim_llms_ownership', 100);

